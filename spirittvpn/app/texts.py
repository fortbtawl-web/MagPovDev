def notice_24h(until: str) -> str:
    return f"⏳ <b>Подписка заканчивается через 24 часа</b>\n\n📅 До: {until}\n\nПродли заранее, чтобы не потерять доступ."


def notice_final(until: str) -> str:
    return f"⏰ <b>Подписка заканчивается сегодня</b>\n\n📅 До: {until}\n\nПродли сейчас — новый срок добавится к текущему."


def notice_expired(trial: bool) -> str:
    if trial:
        return "🎁 <b>Пробный период закончился</b>\n\nДоступ к VPN приостановлен. Выбери тариф, чтобы продолжить."
    return "🔒 <b>Подписка истекла</b>\n\nДоступ к VPN приостановлен. Продли подписку — устройства включатся автоматически."


def referral_reward(days: int, kind: str) -> str:
    why = "активировал пробный период" if kind == "referral_trial" else "оплатил подписку"
    return f"🎁 <b>+{days} дн. к подписке</b>\n\nТвой друг {why}. Спасибо, что делишься SpirittVPN!"


def payment_success(plan: str, until: str, amount: str, order_id: str, test: bool) -> str:
    text = (
        "✅ <b>Оплата подтверждена</b>\n\n"
        f"💳 Тариф: <b>{escape(plan)}</b>\n"
        f"💰 Сумма: {amount}\n"
        f"🧾 Заказ: <code>{order_id}</code>\n"
        f"📅 Подписка: <b>{until}</b>\n\n"
        "Спасибо, что выбрал SpirittVPN!"
    )
    if test:
        text = "🧪 <b>ТЕСТОВАЯ ТРАНЗАКЦИЯ — деньги не списывались</b>\n\n" + text
    return text


